import fs from 'fs';
import path from 'path';

/*
 * The page editor and the page renderer collect the Plate plugins of the
 * add-ons from a `config/plate-editor` and a `config/plate-renderer` module.
 * Each loader imports the module of every add-on that has one, in add-on
 * order, as `[{ addon, module }]`, where `module` is its default export. Only
 * the editor and renderer presets import the loaders, so the plugins stay out
 * of the registry and in the editor and renderer chunks.
 */
export const PLATE_PLUGINS_LOADERS = {
  editor: {
    modulePath: 'config/plate-editor',
    fileName: 'registry.plate.editor.js',
  },
  renderer: {
    modulePath: 'config/plate-renderer',
    fileName: 'registry.plate.renderer.js',
  },
} as const;

const EXTENSIONS = ['.ts', '.tsx', '.js', '.jsx'];

export type PlatePluginsRegistry = {
  projectRootPath: string;
  getAddonDependencies: () => string[];
  packages: Record<string, { modulePath: string; basePath?: string }>;
};

export type PlatePluginsSource = {
  addon: string;
  path: string;
};

/*
 * Finds the add-ons that have a `<modulePath>.{ts,tsx,js,jsx}` file, in
 * add-on order.
 */
export function findPlatePluginsModules(
  registry: PlatePluginsRegistry,
  modulePath: string,
): PlatePluginsSource[] {
  const found: PlatePluginsSource[] = [];
  registry.getAddonDependencies().forEach((addon) => {
    const name = addon.split(':')[0] as string;
    const pkg = registry.packages[name];
    if (!pkg) return;
    const base = path.join(pkg.basePath ?? pkg.modulePath, modulePath);
    const file = EXTENSIONS.map((ext) => `${base}${ext}`).find((candidate) =>
      fs.existsSync(candidate),
    );
    if (file && !found.some((source) => source.addon === name)) {
      found.push({ addon: name, path: file });
    }
  });
  return found;
}

/*
 * The code of a module that imports the given add-on modules and exports
 * them as a list.
 */
export function getPlatePluginsLoaderCode(
  modulePath: string,
  sources: PlatePluginsSource[],
): string {
  const imports = sources.map(
    (source, index) =>
      `import module${index} from ${JSON.stringify(source.path)};`,
  );
  const items = sources.map(
    (source, index) =>
      `  { addon: ${JSON.stringify(source.addon)}, module: module${index} },`,
  );
  return `/*
Don't change this file manually.
It is autogenerated by @plone/registry.
Add a ./${modulePath} module to your add-on to be part of this list.
*/
${imports.join('\n')}

export default [
${items.join('\n')}
];
`;
}

/*
 * Writes the Plate plugins loaders of the editor and the renderer in the
 * project's `.plone` folder and returns their paths. A file is only written
 * when it changes.
 */
export function createPlatePluginsLoaders(registry: PlatePluginsRegistry): {
  editor: string;
  renderer: string;
} {
  const ploneDir = path.join(registry.projectRootPath, '.plone');
  fs.mkdirSync(ploneDir, { recursive: true });

  const write = ({
    modulePath,
    fileName,
  }: (typeof PLATE_PLUGINS_LOADERS)[keyof typeof PLATE_PLUGINS_LOADERS]) => {
    const loaderPath = path.join(ploneDir, fileName);
    const code = getPlatePluginsLoaderCode(
      modulePath,
      findPlatePluginsModules(registry, modulePath),
    );
    const existing = fs.existsSync(loaderPath)
      ? fs.readFileSync(loaderPath, 'utf-8')
      : null;
    if (existing !== code) {
      fs.writeFileSync(loaderPath, code);
    }
    return loaderPath;
  };

  return {
    editor: write(PLATE_PLUGINS_LOADERS.editor),
    renderer: write(PLATE_PLUGINS_LOADERS.renderer),
  };
}
