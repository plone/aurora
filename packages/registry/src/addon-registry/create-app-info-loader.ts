import fs from 'fs';
import path from 'path';

/*
 * The name and version of the app and of its add-ons, collected at build time
 * for `@plone/registry/app-info`. It only has public facts: no paths of the
 * machine that built the app, since the browser loads this module too.
 */
export type AppInfo = {
  name: string;
  version: string;
  addons: Array<{ name: string; version: string }>;
};

export type AppInfoRegistry = {
  packageJson: { name?: string; version?: string };
  getAddons: () => Array<{ name: string; version?: string } | undefined>;
};

export const APP_INFO_LOADER_FILE_NAME = 'registry.appInfo.js';

/*
 * The app and its add-ons, in add-on order.
 */
export function getAppInfo(registry: AppInfoRegistry): AppInfo {
  return {
    name: registry.packageJson.name ?? '',
    version: registry.packageJson.version ?? '',
    addons: registry
      .getAddons()
      .filter((addon) => Boolean(addon))
      .map((addon) => ({
        name: addon!.name,
        version: addon!.version ?? '',
      })),
  };
}

/*
 * The code of a module that exports the app info.
 */
export function getAppInfoLoaderCode(appInfo: AppInfo): string {
  return `/*
Don't change this file manually.
It is autogenerated by @plone/registry.
Instead, change the "name", "version" or "addons" in the app's package.json.
*/
export default ${JSON.stringify(appInfo, null, 2)};
`;
}

/*
 * Writes the app info module in the project's `.plone` folder and returns its
 * path. The file is only written when it changes.
 */
export function createAppInfoLoader(
  registry: AppInfoRegistry & { projectRootPath: string },
): string {
  const ploneDir = path.join(registry.projectRootPath, '.plone');
  fs.mkdirSync(ploneDir, { recursive: true });

  const loaderPath = path.join(ploneDir, APP_INFO_LOADER_FILE_NAME);
  const code = getAppInfoLoaderCode(getAppInfo(registry));
  const existing = fs.existsSync(loaderPath)
    ? fs.readFileSync(loaderPath, 'utf-8')
    : null;
  if (existing !== code) {
    fs.writeFileSync(loaderPath, code);
  }
  return loaderPath;
}
