import fs from 'fs';
import path from 'path';

/*
 * `@plone/registry/addons/<path>` collects the `<path>` module of every
 * add-on that has one, in add-on order, as `[{ addon, module }]`, where
 * `module` is its default export. It is how add-ons contribute code, not
 * configuration, to an extension point: only the code that imports the
 * collection pulls the add-on modules into its chunk, so they stay out of the
 * registry and of the bundles that don't need them.
 */
export const ADDON_MODULES_PREFIX = '@plone/registry/addons/';

const EXTENSIONS = ['.ts', '.tsx', '.js', '.jsx'];

export type AddonModulesRegistry = {
  projectRootPath: string;
  getAddonDependencies: () => string[];
  packages: Record<string, { modulePath: string; basePath?: string }>;
};

export type AddonModuleSource = {
  addon: string;
  path: string;
};

/*
 * Checks that a collected module path is relative and stays inside the
 * add-on, like `config/plate-editor`.
 */
export function validateModulePath(modulePath: string): string {
  const normalized = path.posix.normalize(modulePath);
  if (
    !modulePath ||
    path.posix.isAbsolute(normalized) ||
    normalized.startsWith('..') ||
    path.extname(normalized)
  ) {
    throw new Error(
      `[@plone/registry] "${ADDON_MODULES_PREFIX}${modulePath}" must name a path inside the add-ons, without extension, like "${ADDON_MODULES_PREFIX}config/plate-editor".`,
    );
  }
  return normalized;
}

/*
 * Finds the add-ons that have a `<modulePath>.{ts,tsx,js,jsx}` file, in
 * add-on order.
 */
export function findAddonModules(
  registry: AddonModulesRegistry,
  modulePath: string,
): AddonModuleSource[] {
  const found: AddonModuleSource[] = [];
  registry.getAddonDependencies().forEach((addon) => {
    const name = addon.split(':')[0] as string;
    const pkg = registry.packages[name];
    if (!pkg) return;
    const base = path.join(pkg.basePath ?? pkg.modulePath, modulePath);
    const file = EXTENSIONS.map((ext) => `${base}${ext}`).find((candidate) =>
      fs.existsSync(candidate),
    );
    if (file && !found.some((source) => source.addon === name)) {
      found.push({ addon: name, path: file });
    }
  });
  return found;
}

/*
 * The code of a module that imports the given add-on modules and exports
 * them as a list.
 */
export function getAddonModulesLoaderCode(
  modulePath: string,
  sources: AddonModuleSource[],
): string {
  const imports = sources.map(
    (source, index) =>
      `import module${index} from ${JSON.stringify(source.path)};`,
  );
  const items = sources.map(
    (source, index) =>
      `  { addon: ${JSON.stringify(source.addon)}, module: module${index} },`,
  );
  return `/*
Don't change this file manually.
It is autogenerated by @plone/registry.
Add a ./${modulePath} module to your add-on to be part of this list.
*/
${imports.join('\n')}

export default [
${items.join('\n')}
];
`;
}

/*
 * Writes the collection module for `modulePath` in the project's `.plone`
 * folder and returns its path. The file is only written when it changes, so
 * that resolving it again doesn't trigger a reload.
 */
export function createAddonModulesLoader(
  registry: AddonModulesRegistry,
  modulePath: string,
): string {
  const normalized = validateModulePath(modulePath);
  const loaderPath = path.join(
    registry.projectRootPath,
    '.plone',
    `registry.addons.${normalized.replace(/[^\w-]+/g, '.')}.js`,
  );
  const code = getAddonModulesLoaderCode(
    normalized,
    findAddonModules(registry, normalized),
  );

  fs.mkdirSync(path.dirname(loaderPath), { recursive: true });
  const existing = fs.existsSync(loaderPath)
    ? fs.readFileSync(loaderPath, 'utf-8')
    : null;
  if (existing !== code) {
    fs.writeFileSync(loaderPath, code);
  }
  return loaderPath;
}
